param(
    [ValidateSet('install','load','status','sync','bridge','watch')]
    [string]$Action = 'status'
)
$ErrorActionPreference = 'Stop'
if ($env:OS -ne 'Windows_NT') { throw 'Seelen UI requires Windows.' }

$root = Split-Path $PSScriptRoot -Parent
$theme = Join-Path $root 'integrations\seelen\fox-glass'
$runtime = Join-Path $env:LOCALAPPDATA 'FoxTerminal\foxos'
$syncCss = Join-Path $runtime 'seelen-fox-sync.css'

function Get-FoxStyleAccent {
    $style = Join-Path $runtime 'style.json'
    $accent = '#ed913e'
    $ms = 180
    if (Test-Path -LiteralPath $style) {
        try {
            $j = Get-Content -LiteralPath $style -Raw -Encoding UTF8 | ConvertFrom-Json
            if ($j.colors -and $j.colors.accent) { $accent = [string]$j.colors.accent }
            elseif ($j.accent) { $accent = [string]$j.accent }
            if ($j.motion -and $j.motion.durationMs) { $ms = [int]$j.motion.durationMs }
            elseif ($j.motion -and $j.motion.duration) { $ms = [int]$j.motion.duration }
        } catch {}
    }
    if ($ms -lt 0) { $ms = 0 }
    if ($ms -gt 350) { $ms = 350 }
    return @{ Accent = $accent; MotionMs = $ms }
}

function Write-FoxSeelenSyncCss {
    $c = Get-FoxStyleAccent
    New-Item -ItemType Directory -Force -Path $runtime | Out-Null
    $css = @"
/* Generated by foxseelen sync / FOXSTYLE Apply — do not edit */
:root {
  --fox-accent: $($c.Accent);
  --fox-motion-ms: $($c.MotionMs);
}
"@
    [System.IO.File]::WriteAllText($syncCss, $css, (New-Object System.Text.UTF8Encoding $false))
    # Also stamp shared theme so Seelen picks accent when theme reloads
    $shared = Join-Path $theme 'styles\shared.css'
    if (Test-Path -LiteralPath $shared) {
        $raw = Get-Content -LiteralPath $shared -Raw -Encoding UTF8
        if ($raw -notmatch '--fox-accent-sync') {
            $stamp = "`n/* --fox-accent-sync */`n:root { --fox-accent: $($c.Accent); --fox-motion-ms: $($c.MotionMs); }`n"
            [System.IO.File]::AppendAllText($shared, $stamp, (New-Object System.Text.UTF8Encoding $false))
        } else {
            $raw2 = [regex]::Replace($raw,
                '(?s)/\* --fox-accent-sync \*/.*',
                "/* --fox-accent-sync */`n:root { --fox-accent: $($c.Accent); --fox-motion-ms: $($c.MotionMs); }`n")
            [System.IO.File]::WriteAllText($shared, $raw2, (New-Object System.Text.UTF8Encoding $false))
        }
    }
    return $c
}

if ($Action -eq 'install') {
    if (-not (Get-Command winget -ErrorAction SilentlyContinue)) { throw 'Install Windows App Installer (winget) first.' }
    & winget install --id Seelen.SeelenUI -e --accept-source-agreements --accept-package-agreements --source winget
    if ($LASTEXITCODE -ne 0) {
        & winget install --id Seelen.SeelenUI --exact --accept-source-agreements --accept-package-agreements
    }
    if ($LASTEXITCODE -ne 0) { throw "Seelen installer exited with $LASTEXITCODE. FOX settings were not changed." }
    Write-Host 'Seelen installed. Start Seelen UI, then run: foxseelen load'
    Write-Host 'Keep Nusa for music notch. Avoid enabling a second dock over FoxOS dock.'
    return
}

$slu = Get-Command slu -ErrorAction SilentlyContinue
if (-not $slu) {
    $candidates = @(
        "$env:LOCALAPPDATA\Programs\Seelen\slu.exe",
        "$env:LOCALAPPDATA\Seelen\slu.exe",
        "$env:ProgramFiles\Seelen\slu.exe",
        "$env:LOCALAPPDATA\Microsoft\WinGet\Links\slu.exe"
    )
    foreach ($p in $candidates) {
        if (Test-Path -LiteralPath $p) {
            $slu = @{ Source = $p }
            break
        }
    }
}

if ($Action -eq 'bridge') {
    & (Join-Path $PSScriptRoot 'foxseelen-bridge.ps1') -Once
    return
}
if ($Action -eq 'watch') {
    & (Join-Path $PSScriptRoot 'foxseelen-bridge.ps1') -Watch -Http
    return
}

if ($Action -eq 'status') {
    Write-Host ('Seelen CLI available: ' + [bool]$slu)
    Write-Host ('FOX theme: ' + $theme)
    Write-Host ('Sync CSS:  ' + $syncCss)
    $c = Get-FoxStyleAccent
    Write-Host ("FOXSTYLE accent: $($c.Accent)  motion: $($c.MotionMs)ms")
    Write-Host 'foxseelen install | load | sync | bridge | watch | status'
    Write-Host 'Seelen Settings → Themes → FOX Glass + FOXSTYLE = all FoxStyle controls'
    Write-Host 'Nusa stays for music.'
    return
}

if ($Action -eq 'sync') {
    $c = Write-FoxSeelenSyncCss
    Write-Host ("Synced FOXSTYLE → Seelen: accent=$($c.Accent) motion=$($c.MotionMs)ms")
    if ($slu) {
        try {
            & $slu.Source resource load theme $theme 2>$null
            Write-Host 'Theme reloaded in Seelen session.'
        } catch {
            Write-Host 'Theme files updated; open Seelen and re-select FOX Glass if needed.'
        }
    } else {
        Write-Host 'Seelen not on PATH yet — CSS/theme stamped; run foxseelen load after starting Seelen.'
    }
    return
}

# load
if (-not $slu) { throw 'Start Seelen UI and open a new terminal so slu is on PATH (or re-run after install).' }
Write-FoxSeelenSyncCss | Out-Null
& $slu.Source resource load theme $theme
if ($LASTEXITCODE -ne 0) { throw 'Theme registration failed. FOX settings were not changed.' }
$panel = Join-Path $root 'integrations\seelen\foxstyle-panel'
$plugin = Join-Path $root 'integrations\seelen\fox-apply-plugin'
if (Test-Path $panel) {
    & $slu.Source resource load widget $panel
    Write-Host 'FOXSTYLE panel widget loaded.'
}
if (Test-Path $plugin) {
    & $slu.Source resource load plugin $plugin
    Write-Host 'FOXSTYLE toolbar plugin loaded.'
}
if (Get-Command Disable-SeelenWallpaperOverlay -ErrorAction SilentlyContinue) {
    try { Disable-SeelenWallpaperOverlay | Out-Null } catch {}
} else {
    $settingsPath = Join-Path $env:APPDATA 'com.seelen.seelen-ui\settings.json'
    if (Test-Path -LiteralPath $settingsPath) {
        try {
            $j = Get-Content $settingsPath -Raw -Encoding UTF8 | ConvertFrom-Json
            if ($j.byWidget.'@seelen/wallpaper-manager') {
                $j.byWidget.'@seelen/wallpaper-manager'.enabled = $false
                $utf8 = New-Object System.Text.UTF8Encoding($false)
                [IO.File]::WriteAllText($settingsPath, ($j | ConvertTo-Json -Depth 30), $utf8)
            }
        } catch {}
    }
}
Write-Host 'FOX Glass + FOXSTYLE settings are in Seelen → Themes → FOX Glass + FOXSTYLE.'
Write-Host 'Seelen Wallpaper Manager stays OFF — FoxOS/Shewchuk walls are real Windows wallpapers.'
Write-Host 'Enable toolbar plugin / panel in Seelen settings. Run: foxseelen watch'
Write-Host 'Nusa = music notch. Do not stack Seelen dock on top of FoxOS dock.'
