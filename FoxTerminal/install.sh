#!/usr/bin/env bash
# FoxTerminal -> Ghostty installer for Linux and macOS.
#
# Installs FoxTerminal/ghostty/config as your Ghostty config and generates the
# machine-specific overlay (shell command + repo path) next to it.
set -euo pipefail

FOX_GHOSTTY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/ghostty"
FOX_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOURCE_FILE="${FOX_GHOSTTY_DIR}/config"
BOOT_FILE="${FOX_GHOSTTY_DIR}/foxterminal-boot.sh"

NO_SHORTCUT=0
for arg in "$@"; do
  case "$arg" in
    --no-shortcut) NO_SHORTCUT=1 ;;
    -h|--help)
      printf 'Usage: bash FoxTerminal/install.sh [--no-shortcut]\n'
      exit 0
      ;;
  esac
done

if [ ! -f "${SOURCE_FILE}" ]; then
  printf 'Ghostty config not found: %s\n' "${SOURCE_FILE}" >&2
  exit 1
fi

printf '=== FoxTerminal -> Ghostty ===\n\n'

GHOSTTY_BIN=""
if command -v ghostty >/dev/null 2>&1; then
  GHOSTTY_BIN="$(command -v ghostty)"
elif [ -x /Applications/Ghostty.app/Contents/MacOS/ghostty ]; then
  GHOSTTY_BIN="/Applications/Ghostty.app/Contents/MacOS/ghostty"
fi

if [ -n "${GHOSTTY_BIN}" ]; then
  printf 'Terminal:  ghostty -> %s\n\n' "${GHOSTTY_BIN}"
else
  printf 'Terminal:  not found\n'
  case "$(uname -s)" in
    Darwin) printf '  brew install --cask ghostty\n  or https://ghostty.org/download\n' ;;
    *)      printf '  Install via your package manager, or see https://ghostty.org/download\n' ;;
  esac
  printf '\nThe config will still be installed so it is ready once Ghostty is present.\n\n'
fi

# Resolve the config path: an existing config wins, otherwise the platform default.
CONFIG_FILE=""
CANDIDATES=()
if [ -n "${XDG_CONFIG_HOME:-}" ]; then
  CANDIDATES+=("${XDG_CONFIG_HOME}/ghostty/config.ghostty" "${XDG_CONFIG_HOME}/ghostty/config")
fi
if [ "$(uname -s)" = "Darwin" ]; then
  CANDIDATES+=("${HOME}/Library/Application Support/com.mitchellh.ghostty/config")
fi
CANDIDATES+=("${HOME}/.config/ghostty/config.ghostty" "${HOME}/.config/ghostty/config")

for candidate in "${CANDIDATES[@]}"; do
  if [ -f "${candidate}" ]; then
    CONFIG_FILE="${candidate}"
    break
  fi
done
if [ -z "${CONFIG_FILE}" ]; then
  CONFIG_FILE="${CANDIDATES[0]}"
fi

CONFIG_DIR="$(dirname "${CONFIG_FILE}")"
mkdir -p "${CONFIG_DIR}"

if [ -f "${CONFIG_FILE}" ] && ! grep -q FoxTerminal "${CONFIG_FILE}" 2>/dev/null; then
  BACKUP="${CONFIG_FILE}.backup-$(date +%Y%m%d-%H%M%S)"
  cp "${CONFIG_FILE}" "${BACKUP}"
  printf 'Backed up your previous config to: %s\n' "${BACKUP}"
fi

cp "${SOURCE_FILE}" "${CONFIG_FILE}"
printf 'Installed config: %s\n' "${CONFIG_FILE}"

LOCAL_FILE="${CONFIG_DIR}/foxterminal-local.ghostty"
cat > "${LOCAL_FILE}" <<EOF
# Generated by FoxTerminal/install.sh - do not edit by hand.
# Re-generate by re-running the installer.

env = FOXTERM_ROOT=${FOX_ROOT}
env = FOXTERM_BOOT=${BOOT_FILE}
env = FOXTERM=1
env = FOXTERM_HOST=ghostty

command = bash --noprofile --rcfile ${BOOT_FILE} -i
working-directory = ${FOX_ROOT}

config-file = ?foxterminal-shaders.ghostty
EOF
printf 'Installed local overlay: %s\n' "${LOCAL_FILE}"
printf 'Shell: bash -> %s\n\n' "${BOOT_FILE}"

chmod +x "${BOOT_FILE}" 2>/dev/null || true

if [ -n "${GHOSTTY_BIN}" ]; then
  printf 'Validating config...\n'
  if "${GHOSTTY_BIN}" +show-config 2>&1 | grep -Ei 'error|invalid|unknown field'; then
    printf 'Ghostty reported config problems (see above).\n\n'
  else
    printf 'Config parsed with no errors.\n\n'
  fi

  if [ "${NO_SHORTCUT}" -eq 0 ]; then
    BIN_DIR="${HOME}/.local/bin"
    mkdir -p "${BIN_DIR}"
    cat > "${BIN_DIR}/foxterminal" <<EOF
#!/usr/bin/env bash
exec "${GHOSTTY_BIN}" "\$@"
EOF
    chmod +x "${BIN_DIR}/foxterminal"
    printf 'Created launcher: %s (make sure %s is in PATH)\n' "${BIN_DIR}/foxterminal" "${BIN_DIR}"
  fi
fi

printf '\nNext steps:\n'
printf '  1. Start Ghostty (or press ctrl+shift+comma inside it to reload).\n'
printf '  2. Run "chek" to confirm FoxTerminal sees Ghostty.\n'
printf '  3. "term" manages this config from now on.\n'
