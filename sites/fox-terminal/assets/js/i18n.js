(() => {
  const STORE = "foxterm-site-lang";
  const page = document.body?.dataset?.page || "home";

  function t(key) {
    const lang = window.foxI18n.lang;
    return FOX_I18N[lang]?.[key] ?? FOX_I18N.uk[key] ?? key;
  }

  function apply() {
    document.documentElement.lang = window.foxI18n.lang === "en" ? "en" : "uk";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.dataset.i18n;
      const val = t(key);
      if (val && val !== key) el.textContent = val;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const val = t(el.dataset.i18nPlaceholder);
      if (val) el.placeholder = val;
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      const val = t(el.dataset.i18nHtml);
      if (val) el.innerHTML = val;
    });
    const titleKey = "meta.title." + page;
    if (t(titleKey) !== titleKey) document.title = t(titleKey);

    const brandKey = "brand." + (page === "home" ? "presentation" : page);
    const brandSub = document.querySelector(".brand small");
    if (brandSub && t(brandKey) !== brandKey) brandSub.textContent = t(brandKey);

    const splashSub = document.querySelector(".splash-sub");
    const splashMap = { home: "splash.init", companion: "splash.companion", themes: "splash.themes", commands: "splash.cmds", terminal: "splash.term", ai: "splash.ai", media: "splash.media", hotkeys: "splash.keys", ecosystem: "splash.hub" };
    if (splashSub && splashMap[page]) splashSub.textContent = t(splashMap[page]);

    const langBtn = document.getElementById("lang-toggle");
    if (langBtn) langBtn.textContent = window.foxI18n.lang === "uk" ? "EN" : "UK";

    const themeBtn = document.getElementById("theme-toggle");
    if (themeBtn) themeBtn.textContent = document.body.classList.contains("light") ? t("ui.dark") : t("ui.light");

    const noirToggle = document.getElementById("noir-toggle");
    if (noirToggle) noirToggle.textContent = t("ui.noir");
    const scanToggle = document.getElementById("scan-toggle");
    if (scanToggle) scanToggle.textContent = t("ui.scan");
    const shuffleTheme = document.getElementById("shuffle-theme");
    if (shuffleTheme) shuffleTheme.textContent = "🎲 " + t("ui.random");
    const noirDemo = document.getElementById("noir-demo");
    if (noirDemo) noirDemo.textContent = "◐ " + t("ui.noirdemo");
    const cmdRandom = document.getElementById("cmd-random");
    if (cmdRandom) cmdRandom.textContent = t("cmds.randomBtn");
    const cmdSearch = document.getElementById("cmd-search");
    if (cmdSearch) cmdSearch.placeholder = t("cmds.search");
    const startViz = document.getElementById("start-viz");
    if (startViz && !startViz.dataset.vizRunning) startViz.textContent = "▶ " + t("media.dj.start");

    document.querySelectorAll(".nav a[data-page]").forEach((a) => {
      const key = "nav." + a.dataset.page;
      if (t(key) !== key) a.textContent = t(key);
    });

    document.querySelectorAll(".copy-mini").forEach((btn) => {
      btn.textContent = t("ui.copy");
    });
    document.querySelectorAll("[data-i18n-copy]").forEach((btn) => {
      btn.textContent = t(btn.dataset.i18nCopy);
    });

    document.dispatchEvent(new CustomEvent("foxlangchange", { detail: { lang: window.foxI18n.lang } }));
  }

  function setLang(lang) {
    window.foxI18n.lang = lang === "en" ? "en" : "uk";
    localStorage.setItem(STORE, window.foxI18n.lang);
    apply();
  }

  window.foxI18n = {
    lang: localStorage.getItem(STORE) || "uk",
    t,
    apply,
    setLang
  };

  document.addEventListener("DOMContentLoaded", () => {
    if (!document.getElementById("lang-toggle")) {
      const actions = document.querySelector(".topbar-actions");
      if (actions) {
        const btn = document.createElement("button");
        btn.type = "button";
        btn.id = "lang-toggle";
        btn.className = "btn btn-sm btn-ghost lang-toggle";
        actions.prepend(btn);
        btn.addEventListener("click", () => setLang(window.foxI18n.lang === "uk" ? "en" : "uk"));
      }
    } else {
      document.getElementById("lang-toggle").addEventListener("click", () => setLang(window.foxI18n.lang === "uk" ? "en" : "uk"));
    }
    apply();
  });
})();
